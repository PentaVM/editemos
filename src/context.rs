//! Context pack generator: turns the project's brand, edit brand, memory and
//! assets into one compact markdown document that any agent can read at the
//! start of a session. It is regenerated automatically; nothing is hand-edited.

use crate::assets;
use crate::error::Result;
use crate::memory;
use crate::model::Memory;
use crate::skills;
use crate::store::{Home, Project};
use crate::util::{approx_tokens, ensure_dir, now_iso, truncate_chars, write_atomic};
use std::collections::BTreeMap;
use std::path::Path;

pub struct PackOptions {
    pub task: Option<String>,
    pub budget_tokens: usize,
}

impl Default for PackOptions {
    fn default() -> Self {
        PackOptions { task: None, budget_tokens: 6000 }
    }
}

fn bullet(m: &Memory) -> String {
    let tags = if m.tags.is_empty() { String::new() } else { format!(" [{}]", m.tags.join(", ")) };
    format!("- ({}, {}) {}{}", m.kind, m.confidence, m.text.replace('\n', " "), tags)
}

pub fn build(home: &Home, p: &Project, opts: &PackOptions) -> String {
    let brand = p.load_brand();
    let mems = memory::active(p);
    let assets = assets::load(p);
    let mut sections: Vec<(u8, String)> = Vec::new();

    let mut head = format!("# {} — editing context\n\n", p.config.name);
    head.push_str(&format!(
        "> Generated by editemos at {}. Source of truth: `{}`. Do not edit this file; record knowledge with `editemos memory add` (or the `editemos_memory_add` tool).\n\n",
        now_iso(),
        p.dir.display()
    ));
    head.push_str("## How to work in this project\n\n");
    head.push_str("1. This project has its own edit brand. Do not reuse another project's motion, type or cuts.\n");
    head.push_str("2. Follow the edit brand rules below; when you must break one, say why and write a memory.\n");
    head.push_str("3. Generic motion (fade plus small slide-up, rounded lower-third with accent bar, crossfade everywhere, idle wobble) is off the table.\n");
    head.push_str("4. When the user decides, rejects or prefers something, call `editemos_memory_add` right away. Chat history is not memory.\n");
    head.push_str("5. Source media is read-only. Renders go to `motion/renders` or the job folder, with new file names.\n");
    sections.push((0, head));

    // what this person wants in every project, whoever the client is
    let prefs = crate::fonts::load_prefs(home);
    let user = Project { dir: home.root.join("user"), config: Default::default() };
    let user_mems = memory::active(&user);
    if !user_mems.is_empty() || prefs.caption_font.is_some() || !prefs.rejected_fonts.is_empty() {
        let mut u = String::from("## The user's standing preferences (all projects)\n\n");
        if let Some(f) = &prefs.caption_font {
            u.push_str(&format!("- Preferred typeface for on-screen text: {f}\n"));
        }
        if !prefs.rejected_fonts.is_empty() {
            u.push_str(&format!("- Never use these typefaces: {}\n", prefs.rejected_fonts.join(", ")));
        }
        for m in user_mems.iter().rev().take(20) {
            u.push_str(&bullet(m));
            u.push('\n');
        }
        u.push('\n');
        sections.push((1, u));
    }

    // brand
    let mut b = String::from("## Brand\n\n");
    b.push_str(&format!("- Name: {}\n", brand.name));
    if let Some(u) = &brand.source_url {
        b.push_str(&format!("- Site: {u}\n"));
    }
    if let Some(t) = &brand.tagline {
        b.push_str(&format!("- Tagline: {t}\n"));
    }
    if let Some(d) = &brand.description {
        b.push_str(&format!("- About: {}\n", truncate_chars(d, 240)));
    }
    if !brand.voice.descriptors.is_empty() {
        b.push_str(&format!("- Voice: {}\n", brand.voice.descriptors.join(", ")));
    }
    if !brand.voice.samples.is_empty() {
        b.push_str("- Voice samples:\n");
        for s in brand.voice.samples.iter().take(4) {
            b.push_str(&format!("  - \"{}\"\n", truncate_chars(s, 120)));
        }
    }
    if !brand.palette.is_empty() {
        let pal: Vec<String> = brand.palette.iter().take(8).map(|c| format!("{} {}", c.role, c.hex)).collect();
        b.push_str(&format!("- Palette: {}\n", pal.join(" · ")));
    }
    if !brand.fonts.is_empty() {
        let f: Vec<String> = brand.fonts.iter().take(5).map(|f| format!("{} ({})", f.family, f.role)).collect();
        b.push_str(&format!("- Fonts: {}\n", f.join(", ")));
    }
    sections.push((1, b));

    // edit brand
    let e = &brand.edit;
    if !e.tempo.is_empty() {
        let mut s = String::from("## Edit brand (how this project moves)\n\n");
        s.push_str(&format!("- Tempo: **{}** (seed {})\n", e.tempo, e.seed));
        s.push_str(&format!("- Easings (cubic-bezier): enter {:?}, exit {:?}, travel {:?}, impact {:?}\n", e.easings.enter, e.easings.exit, e.easings.travel, e.easings.impact));
        s.push_str(&format!(
            "- Duration palette (frames @30fps): {:?}; stagger {} ms, each gap x{}; hold {} frames before a climax\n",
            e.durations, e.stagger_ms, e.stagger_shrink, e.hold_frames
        ));
        if let Some(st) = e.step_fps {
            s.push_str(&format!("- Graphics animate on {st} fps steps\n"));
        }
        s.push_str(&format!("- Transition vocabulary: {}\n", e.transitions.join(", ")));
        s.push_str(&format!(
            "- Type: heading {}, body {}, mono {}, weight range {}-{}\n",
            e.type_tokens.heading, e.type_tokens.body, e.type_tokens.mono, e.type_tokens.weight_range[0], e.type_tokens.weight_range[1]
        ));
        s.push_str(&format!("- Colours: bg {} · fg {} · accent {} · accent2 {} · muted {}\n", e.colors.bg, e.colors.fg, e.colors.accent, e.colors.accent2, e.colors.muted));
        s.push_str("\nRules:\n");
        for r in &e.rules {
            s.push_str(&format!("- {r}\n"));
        }
        sections.push((2, s));
    } else {
        sections.push((2, "## Edit brand\n\nNot derived yet. Run `editemos extract <url>` or `editemos brand derive`.\n".to_string()));
    }

    // standing rules = pinned or high-confidence preferences/rejections/decisions
    let standing: Vec<&Memory> = mems.iter().filter(|m| m.pinned || (m.confidence == "high" && matches!(m.kind.as_str(), "preference" | "rejection" | "decision"))).collect();
    if !standing.is_empty() {
        let mut s = String::from("## Standing rules (from this project's memory)\n\n");
        for m in standing.iter().take(24) {
            s.push_str(&bullet(m));
            s.push('\n');
        }
        sections.push((3, s));
    }

    // task-relevant memory
    if let Some(task) = &opts.task {
        let hits = memory::search(&mems, task, 8);
        let stand_ids: Vec<&str> = standing.iter().map(|m| m.id.as_str()).collect();
        let hits: Vec<_> = hits.into_iter().filter(|(_, m)| !stand_ids.contains(&m.id.as_str())).collect();
        if !hits.is_empty() {
            let mut s = format!("## Memory relevant to: {}\n\n", truncate_chars(task, 100));
            for (_, m) in hits {
                s.push_str(&bullet(&m));
                s.push('\n');
            }
            sections.push((4, s));
        }
    }

    // recent decisions
    let mut recent: Vec<&Memory> = mems.iter().filter(|m| m.kind == "decision" || m.kind == "run").collect();
    recent.reverse();
    if !recent.is_empty() {
        let mut s = String::from("## Recent decisions and runs\n\n");
        for m in recent.iter().take(8) {
            s.push_str(&format!("- {} {}\n", m.ts.get(..10).unwrap_or(""), truncate_chars(&m.text.replace('\n', " "), 200)));
        }
        sections.push((5, s));
    }

    // assets
    if !assets.is_empty() {
        let mut counts: BTreeMap<&str, usize> = BTreeMap::new();
        for a in &assets {
            *counts.entry(a.kind.as_str()).or_insert(0) += 1;
        }
        let mut s = String::from("## Assets\n\n");
        s.push_str(&format!(
            "Catalog at `{}` ({} files): {}\n\n",
            p.assets_dir().display(),
            assets.len(),
            counts.iter().map(|(k, v)| format!("{k} {v}")).collect::<Vec<_>>().join(", ")
        ));
        for a in assets.iter().filter(|a| a.kind == "logo").chain(assets.iter().filter(|a| a.kind != "logo")).take(10) {
            s.push_str(&format!(
                "- {} `{}` {}x{} {}{}\n",
                a.kind,
                a.file,
                a.width,
                a.height,
                a.colors.iter().take(3).cloned().collect::<Vec<_>>().join(" "),
                if a.origin == "generated" { " (generated)" } else { "" }
            ));
        }
        sections.push((6, s));
    }

    // motion library: what already exists is reused, not rebuilt
    let pieces = crate::motion::library::load(p);
    if !pieces.is_empty() {
        let mut s = String::from("## Motion library (reuse before making anything new)\n\nThese graphics already exist for this project. Use them again, or adapt the scene file, rather than writing another script that does the same job.\n\n");
        for x in pieces.iter().rev().take(15) {
            let r = x.renders.last().map(|r| format!(" -> `{}` ({:.1}s)", r.file, r.duration)).unwrap_or_else(|| " (not rendered yet)".into());
            s.push_str(&format!("- {} \"{}\" `{}`{}\n", x.kind, truncate_chars(&x.text, 40), x.scene, r));
        }
        sections.push((5, s));
    }

    // skills
    let sk = skills::enabled(home, p);
    if !sk.is_empty() {
        let mut s = String::from("## Skills enabled for this project\n\nRead a skill's SKILL.md when its topic comes up.\n\n");
        for k in sk.iter().take(30) {
            s.push_str(&format!("- **{}** ({}): {} — `{}`\n", k.name, k.id, k.description, k.skill_md));
        }
        sections.push((7, s));
    }

    // tools
    let tools = "## Tools\n\n\
MCP server `editemos` (stdio: `editemos serve`) exposes: `editemos_project`, `editemos_context`, `editemos_memory_add`, `editemos_memory_search`, `editemos_brand`, `editemos_assets`, `editemos_extract`, `editemos_generate`, `editemos_motion`, `editemos_kdenlive`, `editemos_skills`.\n\
Every tool also exists as a CLI command (`editemos --help`).\n";
    sections.push((8, tools.to_string()));

    // assemble within budget: drop the lowest-priority sections first
    let mut keep: Vec<(u8, String)> = sections;
    loop {
        let total: usize = keep.iter().map(|(_, s)| approx_tokens(s)).sum();
        if total <= opts.budget_tokens || keep.len() <= 3 {
            break;
        }
        let max_pri = keep.iter().map(|(p, _)| *p).max().unwrap_or(0);
        if let Some(pos) = keep.iter().rposition(|(p, _)| *p == max_pri) {
            keep.remove(pos);
        }
    }
    keep.sort_by_key(|(p, _)| *p);
    keep.into_iter().map(|(_, s)| s).collect::<Vec<_>>().join("\n")
}

/// Write CONTEXT.md and the per-agent entry files into `dir`.
pub fn write_agent_files(home: &Home, p: &Project, dir: &Path, opts: &PackOptions) -> Result<Vec<String>> {
    ensure_dir(dir)?;
    let body = build(home, p, opts);
    let mut written = Vec::new();
    for (name, prefix) in [
        ("CONTEXT.md", ""),
        ("CLAUDE.md", "<!-- editemos: project context for Claude Code -->\n"),
        ("AGENTS.md", "<!-- editemos: project context for Codex and other AGENTS.md readers -->\n"),
        ("GEMINI.md", "<!-- editemos: project context for Gemini CLI -->\n"),
    ] {
        write_atomic(&dir.join(name), format!("{prefix}{body}").as_bytes())?;
        written.push(dir.join(name).to_string_lossy().to_string());
    }
    Ok(written)
}

/// Regenerate the project's own context directory (cheap; called after every change).
pub fn refresh(home: &Home, p: &Project) -> Result<()> {
    write_agent_files(home, p, &p.context_dir(), &PackOptions::default()).map(|_| ())
}

#[cfg(test)]
mod tests {
    use super::*;
    use crate::memory;

    #[test]
    fn pack_includes_rules_and_respects_budget() {
        let _g = crate::util::ENV_LOCK.lock().unwrap_or_else(|e| e.into_inner());
        let tmp = std::env::temp_dir().join(format!("editemos-ctx-{}", crate::util::short_id()));
        std::env::set_var("EDITEMOS_HOME", &tmp);
        let home = Home::open().unwrap();
        let p = home.create("Ctx Test", None).unwrap();
        memory::add(&p, "Never use crossfades between interview cuts", "rejection", vec!["cuts".into()], "high", "user", true, None).unwrap();
        for i in 0..40 {
            memory::add(&p, &format!("note number {i} about grain and pacing"), "note", vec![], "low", "agent", false, None).unwrap();
        }
        let full = build(&home, &p, &PackOptions::default());
        assert!(full.contains("Never use crossfades"));
        assert!(full.contains("How to work in this project"));
        let tiny = build(&home, &p, &PackOptions { task: Some("grain".into()), budget_tokens: 150 });
        assert!(approx_tokens(&tiny) < approx_tokens(&full));
        let _ = std::fs::remove_dir_all(&tmp);
    }
}
